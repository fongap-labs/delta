/**
 * Pure rendering of the legacy alias stylesheet from the frozen contract in
 * `legacy-tokens.json`. `scripts/gen-token-aliases.ts` writes the
 * result to `styles/legacy-plugin-aliases.css`; specs compare against it.
 * Not imported by the runtime.
 *
 * Custom properties compute per element. Names the host declares only on
 * `:root`/`body` alias once there, which follows `body[data-ds-dark-theme]`
 * and inline theme overrides. Names the host re-declares below `body`
 * (slot variables, elevation, focus-ring, scrollbar and similar tokens)
 * alias on every element so a read resolves against the element's own value.
 */
import { LEGACY_TOKEN_PREFIX, normalizeLegacyTokenName } from './legacy-tokens.ts'

/** Shape of the frozen contract. */
export interface LegacyTokenContract {
  /** Legacy names the host declares only on `:root` or `body`. */
  readonly global: readonly string[]
  /** Legacy names the host also re-declares on descendant elements. */
  readonly element: readonly string[]
}

/**
 * Validate the contract: legacy-prefixed, unique, sorted per scope.
 * @param contract - frozen legacy name lists.
 * @returns problems found; empty when the contract is well formed.
 */
export function contractProblems(contract: LegacyTokenContract): string[] {
  const problems: string[] = []
  const seen = new Set<string>()
  for (const [scope, names] of [['global', contract.global], ['element', contract.element]] as const) {
    const sorted = [...names].sort()
    if (sorted.some((name, index) => name !== names[index])) problems.push(`${scope} names are not sorted`)
    for (const name of names) {
      if (!LEGACY_TOKEN_PREFIX.test(name)) problems.push(`${name} has no legacy prefix`)
      if (seen.has(name)) problems.push(`${name} is listed twice`)
      seen.add(name)
    }
  }
  return problems
}

/**
 * Render the alias stylesheet for a contract.
 * @param contract - frozen legacy name lists.
 * @returns stylesheet text with `\n` line endings.
 */
export function renderAliases(contract: LegacyTokenContract): string {
  const block = (names: readonly string[]): string =>
    names.map(name => `  ${name}: var(${normalizeLegacyTokenName(name)});`).join('\n')
  return [
    '/*',
    ' * Generated by scripts/gen-token-aliases.ts from legacy-tokens.json —',
    ' * do not edit by hand; run `pnpm run gen-legacy-token-aliases` to regenerate.',
    ' * Compatibility reads for third-party plugins written against the token',
    ' * prefixes that preceded `--delta-`. Host styles never read these names.',
    ' */',
    '',
    ':root,',
    'body {',
    block(contract.global),
    '}',
    '',
    '/* Re-declared below body by host components: resolve at each element. */',
    '*,',
    '::before,',
    '::after {',
    block(contract.element),
    '}',
    '',
  ].join('\n')
}
